CREATE EXTENSION IF NOT EXISTS unaccent;

DROP TABLE IF EXISTS sync_logs, inventory_stock, books, bookstores CASCADE;

-- 1. BOOKSTORES: librerías y cómo se sincroniza su stock
CREATE TABLE bookstores (
    bookstore_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             TEXT NOT NULL,
    website          TEXT,
    whatsapp         VARCHAR(20),   -- Formato internacional sin '+', ej. 59899123456
    instagram        VARCHAR(100),  -- Usuario de Instagram, sin '@'
    specialty        TEXT NOT NULL, -- Géneros separados por coma
    address          TEXT NOT NULL,
    department       TEXT NOT NULL,
    latitude         NUMERIC(10, 6),
    longitude        NUMERIC(10, 6),
    ingestion_method VARCHAR(50) NOT NULL DEFAULT 'web_scraper', -- 'web_scraper' | 'google_sheets'
    sheet_url        TEXT,          -- Enlace CSV de la planilla de stock (librerías 'google_sheets')
    sync_frequency   VARCHAR(50) NOT NULL DEFAULT 'twice_weekly',
    featured         BOOLEAN NOT NULL DEFAULT false,
    is_active        BOOLEAN NOT NULL DEFAULT true,
    osm_id           VARCHAR(30),   -- ID en OpenStreetMap (librerías descubiertas por seed_stores.py)
    discovered_at    TIMESTAMPTZ    -- Cuándo la encontró la búsqueda semanal (NULL: cargada a mano)
);
CREATE UNIQUE INDEX ux_bookstores_osm_id ON bookstores (osm_id) WHERE osm_id IS NOT NULL;

-- 2. BOOKS: catálogo maestro (deduplicado por ISBN cuando existe)
CREATE TABLE books (
    book_id   INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    isbn      VARCHAR(20),
    title     TEXT NOT NULL,
    author    TEXT,
    genre     TEXT,
    cover_url TEXT
);
CREATE UNIQUE INDEX ux_books_isbn ON books (isbn) WHERE isbn IS NOT NULL;
CREATE INDEX ix_books_title_author ON books (title, (COALESCE(author, '')));

-- 3. INVENTORY_STOCK: oferta de cada librería (precio, stock, enlace)
CREATE TABLE inventory_stock (
    stock_id       INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bookstore_id   INTEGER NOT NULL REFERENCES bookstores (bookstore_id) ON DELETE CASCADE,
    book_id        INTEGER NOT NULL REFERENCES books (book_id) ON DELETE CASCADE,
    price_uyu      NUMERIC(10, 2),
    stock_quantity INTEGER NOT NULL DEFAULT 1,
    condition      VARCHAR(50) NOT NULL DEFAULT 'Nuevo', -- 'Nuevo' | 'Usado'
    product_url    TEXT,
    external_id    VARCHAR(150), -- ID del producto en el sitio de la librería (o 'sheet:<isbn>:<estado>')
    last_updated   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_inventory_store_external ON inventory_stock (bookstore_id, external_id)
    WHERE external_id IS NOT NULL;
CREATE INDEX ix_inventory_book ON inventory_stock (book_id);

-- 4. SYNC_LOGS: auditoría de cada sincronización (scrapers y planillas)
CREATE TABLE sync_logs (
    log_id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bookstore_id      INTEGER REFERENCES bookstores (bookstore_id) ON DELETE SET NULL,
    sync_channel      VARCHAR(50) NOT NULL, -- 'web_scraper' | 'google_sheets'
    status            VARCHAR(50) NOT NULL, -- 'success' | 'partial' | 'failed'
    records_processed INTEGER NOT NULL DEFAULT 0,
    executed_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_sync_logs_store_time ON sync_logs (bookstore_id, executed_at DESC);

